"""An opt-in, reversible guard at the user's existing Claude CLI entry point.

This is entry-point integration, not an OS execution sandbox. A deliberately
invoked native version binary remains outside this wrapper's coverage.
"""
from __future__ import annotations

from contextlib import contextmanager
import ctypes
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shlex
import re
import subprocess
import stat
import sys
import tempfile

from .core import APP_SUPPORT, Blocked

MARKER = "# Surge CC managed Claude entry v1"
_FIELDS = {"schema", "command_path", "original_link", "original_path", "original_stat",
           "entrypoint", "python_executable", "config_path", "shim_sha256", "native_version"}


def _state_dir(value=None):
    return Path(value) if value is not None else APP_SUPPORT / "terminal"


def _plain_path(path: Path, *, leaf=True):
    if not path.is_absolute() or any(ord(c) < 32 for c in str(path)) or ".." in path.parts:
        raise Blocked("终端集成路径必须是无控制字符的绝对路径。")
    points = (path, *path.parents) if leaf else path.parents
    if any(p.is_symlink() for p in points):
        raise Blocked("终端集成的配置、后端和父目录不能使用符号链接。")


def _private_dir(path: Path, *, create=False):
    _plain_path(path)
    if create:
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
    info = path.stat()
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o077:
        raise Blocked("终端集成状态目录必须由当前用户持有且权限为 700。")


def _regular(path: Path, *, executable=False):
    _plain_path(path)
    info = path.stat()
    if (not stat.S_ISREG(info.st_mode) or info.st_uid not in (0, os.getuid())
            or info.st_mode & 0o022 or (executable and not os.access(path, os.X_OK))):
        raise Blocked("终端集成所需文件不可用或允许其他用户修改，已阻止启动。")
    return info


def _identity(path: Path):
    info = _regular(path, executable=True)
    return [info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns]


def _prefix(path):
    with path.open("rb") as stream:
        return stream.read(256)


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _shim(manifest):
    q = shlex.quote
    backend, python, config = (q(manifest[k]) for k in ("entrypoint", "python_executable", "config_path"))
    return (f"#!/bin/sh\n{MARKER}\n"
            "# Generated by Surge CC. No direct-binary fallback.\n"
            f"if [ ! -x {python} ] || [ ! -f {backend} ] || [ ! -f {config} ] || "
            f"[ -L {backend} ] || [ -L {config} ]; then\n"
            "  printf '%s\\n' 'Surge CC: protected launcher unavailable; launch blocked.' >&2\n"
            "  exit 78\nfi\n"
            f'if [ "$#" -eq 1 ] && {{ [ "$1" = "--version" ] || [ "$1" = "-v" ]; }}; then\n'
            f"  exec {python} {backend} --config {config} terminal version\nfi\n"
            "printf '%s\\n' 'Surge CC: checking protected Claude route…' >&2\n"
            "SURGE_CC_TERMINAL_ENTRY=1\nexport SURGE_CC_TERMINAL_ENTRY\n"
            f"exec {python} {backend} --config {config} launch code --passthrough -- \"$@\"\n").encode()


@contextmanager
def _lock(folder: Path):
    _private_dir(folder, create=True)
    lock_path = folder / ".lock"
    _plain_path(lock_path)
    fd = os.open(lock_path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o077:
            raise Blocked("终端集成锁文件不安全。")
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        os.close(fd)


def _exchange(first: Path, second: Path):
    """Atomically exchange two entries, preserving the displaced entry for validation."""
    libc = ctypes.CDLL(None, use_errno=True)
    if sys.platform == "darwin":
        func = libc.renameatx_np
    else:
        func = getattr(libc, "renameat2", None)
        if func is None:
            raise Blocked("当前系统不支持安全的原子入口替换。")
    func.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
    func.restype = ctypes.c_int
    # AT_FDCWD is platform-specific; both paths are absolute.
    cwd = -2 if sys.platform == "darwin" else -100
    if func(cwd, os.fsencode(first), cwd, os.fsencode(second), 2) != 0:
        error = ctypes.get_errno()
        raise OSError(error, os.strerror(error))


def _read(folder: Path):
    _private_dir(folder)
    file = folder / "manifest.json"
    info = _regular(file)
    if info.st_uid != os.getuid() or info.st_mode & 0o077 or info.st_size > 16384:
        raise Blocked("终端集成记录权限或大小不正确。")
    data = json.loads(file.read_text())
    if not isinstance(data, dict) or set(data) != _FIELDS or type(data.get("schema")) is not int or data.get("schema") != 1:
        raise Blocked("终端集成记录损坏，已阻止启动；请先修复集成。")
    for key in ("command_path", "original_path", "entrypoint", "python_executable", "config_path"):
        if not isinstance(data[key], str):
            raise Blocked("终端集成记录的路径无效。")
        _plain_path(Path(data[key]), leaf=key != "command_path")
    if not isinstance(data["original_link"], str) or not data["original_link"] or any(ord(c) < 32 for c in data["original_link"]):
        raise Blocked("终端集成原始入口记录无效。")
    if (not isinstance(data["original_stat"], list) or len(data["original_stat"]) != 4
            or any(type(v) is not int or v < 0 for v in data["original_stat"])):
        raise Blocked("终端集成原始程序记录无效。")
    if not isinstance(data["native_version"], str) or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+ \(Claude Code\)", data["native_version"]) or len(data["native_version"]) > 100:
        raise Blocked("终端集成版本记录无效。")
    if data["shim_sha256"] != _digest(_shim(data)):
        raise Blocked("终端集成入口记录不一致。")
    backup = folder / "original-link"
    if not backup.is_symlink() or os.readlink(backup) != data["original_link"]:
        raise Blocked("终端集成的原始入口备份被修改，已阻止启动。")
    expected = (Path(data["command_path"]).parent / data["original_link"]).resolve()
    # st_dev identifies the current mount, not a persistent volume identity; on
    # macOS it can change across a reboot/remount while the file is unchanged.
    # Retain the four-field schema for existing installations, but compare only
    # inode, size and mtime here. _identity still checks the path, owner, mode and
    # executability. Short-lived race/atomic-exchange checks below must continue
    # comparing st_dev as well, because both snapshots share the same mount.
    if expected != Path(data["original_path"]) or _identity(expected)[1:] != data["original_stat"][1:]:
        raise Blocked("原始 Claude 程序已变化；请通过维护流程重新安装终端集成。")
    return data


def _verify_active(data):
    command = Path(data["command_path"])
    info = _regular(command, executable=True)
    if info.st_uid != os.getuid() or info.st_mode & 0o077 or info.st_size != len(_shim(data)) or command.read_bytes() != _shim(data):
        raise Blocked("Claude 命令入口已被修改，终端保护不完整。")
    _regular(Path(data["entrypoint"]))
    _regular(Path(data["python_executable"]), executable=True)
    _regular(Path(data["config_path"]))


def _write_private(path, data, *, mode=0o600):
    fd, name = tempfile.mkstemp(prefix=".terminal-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            os.fchmod(stream.fileno(), mode)
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.lexists(name):
            os.unlink(name)


def _safe_error(error):
    return error if isinstance(error, Blocked) else Blocked("无法验证终端集成；已阻止启动，请检查集成状态。")


def original_claude(candidate: Path, *, state_dir=None) -> Path:
    """Return the preserved executable only when the installed entry is intact."""
    folder = _state_dir(state_dir)
    try:
        if not folder.exists() and not folder.is_symlink():
            if candidate.is_file():
                with candidate.open("rb") as handle:
                    if MARKER.encode() in handle.read(256):
                        raise Blocked("Claude 入口属于 Surge CC，但集成记录缺失，已阻止启动。")
            return candidate
        _private_dir(folder)
        if not (folder / "manifest.json").exists() and not (folder / "manifest.json").is_symlink():
            # A clean uninstall retains a lock file only; all other residue is unsafe.
            if any(p.name != ".lock" for p in folder.iterdir()):
                raise Blocked("终端集成记录不完整，已阻止启动。")
            if candidate.is_file() and MARKER.encode() in _prefix(candidate):
                raise Blocked("Claude 入口属于 Surge CC，但集成记录缺失，已阻止启动。")
            return candidate
        data = _read(folder)
        _verify_active(data)
        return Path(data["original_path"]) if candidate == Path(data["command_path"]) else candidate
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError, Blocked) as error:
        raise _safe_error(error) from None


def status(*, state_dir=None) -> dict:
    folder = _state_dir(state_dir)
    try:
        if not folder.exists() and not folder.is_symlink():
            return {"ok": True, "installed": False, "summary": "尚未安装终端入口保护。"}
        _private_dir(folder)
        if not (folder / "manifest.json").exists() and set(p.name for p in folder.iterdir()) <= {".lock"}:
            return {"ok": True, "installed": False, "summary": "尚未安装终端入口保护。"}
        data = _read(folder)
        _verify_active(data)
        return {"ok": True, "installed": True, "command_path": data["command_path"],
                "original_path": data["original_path"], "summary": "终端命令已接入 Surge CC。"}
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError, Blocked) as error:
        return {"ok": False, "installed": True, "summary": str(_safe_error(error))}


def install(config_path: Path, entrypoint: Path, python_executable: Path, *, command_path=None, state_dir=None) -> dict:
    command = Path(command_path) if command_path is not None else Path.home() / ".local/bin/claude"
    folder = _state_dir(state_dir)
    try:
        _plain_path(command, leaf=False)
        for path in (config_path, entrypoint):
            _regular(Path(path))
        _regular(Path(python_executable), executable=True)
        parent = command.parent.stat()
        if parent.st_uid != os.getuid() or parent.st_mode & 0o022:
            raise Blocked("Claude 命令目录必须由当前用户持有且不可被其他用户修改。")
        with _lock(folder):
            if (folder / "manifest.json").exists() or (folder / "manifest.json").is_symlink():
                data = _read(folder)
                _verify_active(data)
                requested = {"command_path": str(command), "config_path": str(config_path),
                             "entrypoint": str(entrypoint), "python_executable": str(python_executable)}
                if any(data[k] != v for k, v in requested.items()):
                    raise Blocked("已有不同的终端集成；请先卸载后重新安装。")
                return status(state_dir=folder)
            if set(p.name for p in folder.iterdir()) != {".lock"}:
                raise Blocked("终端集成目录存在未完成的记录，请先检查，未覆盖任何入口。")
            if not command.is_symlink():
                raise Blocked("只支持接管现有 Claude 官方符号链接入口，未修改当前文件。")
            before = command.lstat()
            if before.st_uid != os.getuid():
                raise Blocked("Claude 原始入口不属于当前用户。")
            link = os.readlink(command)
            original = command.resolve(strict=True)
            if original == command or MARKER.encode() in _prefix(original):
                raise Blocked("原始 Claude 入口不能指向另一个 Surge CC 包装器。")
            data = {"schema": 1, "command_path": str(command), "original_link": link,
                    "original_path": str(original), "original_stat": _identity(original),
                    "entrypoint": str(entrypoint), "python_executable": str(python_executable),
                    "config_path": str(config_path)}
            version_env = dict(os.environ, DISABLE_AUTOUPDATER="1")
            capture = subprocess.run([str(original), "--version"], env=version_env,
                                     stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=5)
            version = capture.stdout.strip()
            if capture.returncode != 0 or len(version) > 100 or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+ \(Claude Code\)", version):
                raise Blocked("无法识别原始 Claude Code 版本，未修改命令入口。")
            data["native_version"] = version
            body = _shim(data)
            data["shim_sha256"] = _digest(body)
            backup = folder / "original-link"
            backup.symlink_to(link)
            _write_private(folder / "manifest.json", (json.dumps(data, indent=2) + "\n").encode())
            fd, temp_name = tempfile.mkstemp(prefix=".surge-cc-entry-", dir=command.parent)
            temp = Path(temp_name)
            swapped = False
            preserve_displaced = False
            try:
                with os.fdopen(fd, "wb") as stream:
                    os.fchmod(stream.fileno(), 0o700)
                    stream.write(body)
                    stream.flush()
                    os.fsync(stream.fileno())
                _exchange(temp, command)
                swapped = True
                displaced = temp.lstat()
                if (not temp.is_symlink() or (displaced.st_dev, displaced.st_ino) != (before.st_dev, before.st_ino)
                        or os.readlink(temp) != link):
                    # Restore what actually occupied the entry, never overwrite an intervening edit.
                    preserve_displaced = True
                    if command.is_file() and not command.is_symlink() and command.read_bytes() == body:
                        _exchange(temp, command)
                        swapped = False
                        preserve_displaced = False
                    raise Blocked("安装期间 Claude 入口发生变化，已取消安装；请检查当前入口。")
                _verify_active(data)
            except BaseException:
                if not swapped:
                    (folder / "manifest.json").unlink()
                    backup.unlink()
                # On an uncertain post-swap failure retain the recovery manifest.
                raise
            finally:
                if os.path.lexists(temp) and not preserve_displaced:
                    temp.unlink()
            return status(state_dir=folder)
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError, Blocked) as error:
        raise _safe_error(error) from None


def _update_signature(info):
    return (info.st_dev, info.st_ino, info.st_mode, info.st_uid,
            info.st_size, info.st_mtime_ns)


def _update_snapshot(path: Path):
    """Read a bounded private regular file without following its final entry."""
    _plain_path(path)
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as stream:
        info = os.fstat(stream.fileno())
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                or info.st_mode & 0o077 or info.st_size > 16384):
            raise Blocked("终端更新文件不安全，已取消更新。")
        body = stream.read(16385)
        if (len(body) != info.st_size or _update_signature(os.fstat(stream.fileno())) != _update_signature(info)
                or _update_signature(path.lstat()) != _update_signature(info)):
            raise Blocked("终端更新期间文件发生变化，已取消更新。")
    return _update_signature(info), body


def _update_matches(path: Path, snapshot):
    try:
        return _update_snapshot(path) == snapshot
    except (OSError, ValueError, Blocked):
        return False


def _update_restore(entry):
    """Restore a displaced entry only while our replacement still occupies it."""
    target, staging = entry["target"], entry["staging"]
    if not _update_matches(target, entry["new"]):
        return
    displaced = _update_signature(staging.lstat())
    _exchange(staging, target)
    if _update_matches(staging, entry["new"]):
        entry["swapped"] = False
        return
    # A concurrent edit arrived after the ownership check. Put it back if the
    # restored entry is still the one we just moved; otherwise keep both files.
    if _update_signature(target.lstat()) == displaced:
        _exchange(staging, target)


def update_backend(entrypoint: Path, python_executable: Path | None = None, *, state_dir=None) -> dict:
    """Rebind an intact managed entry without exposing the native Claude link.

    Each file exchange is atomic. Between the shim and manifest exchanges their
    mismatch blocks original_claude. Displaced files stay on disk until commit,
    and rollback checks ownership while preserving concurrent user edits.
    """
    folder = _state_dir(state_dir)
    try:
        entrypoint = Path(entrypoint)
        _regular(entrypoint)
        if python_executable is not None:
            python_executable = Path(python_executable)
            _regular(python_executable, executable=True)
        _private_dir(folder)
        with _lock(folder):
            data = _read(folder)
            _verify_active(data)
            command = Path(data["command_path"])
            manifest = folder / "manifest.json"
            parent = command.parent.stat()
            if parent.st_uid != os.getuid() or parent.st_mode & 0o022:
                raise Blocked("Claude 命令目录必须由当前用户持有且不可被其他用户修改。")
            old_manifest = _update_snapshot(manifest)
            old_shim = _update_snapshot(command)
            if json.loads(old_manifest[1]) != data or old_shim[1] != _shim(data):
                raise Blocked("终端更新期间文件发生变化，已取消更新。")
            updated = dict(data, entrypoint=str(entrypoint),
                           python_executable=str(python_executable) if python_executable is not None
                           else data["python_executable"])
            if updated == data:
                return status(state_dir=folder)
            body = _shim(updated)
            updated["shim_sha256"] = _digest(body)
            manifest_body = (json.dumps(updated, indent=2) + "\n").encode()
            entries = []
            committed = False
            try:
                for target, old, contents, mode in ((command, old_shim, body, 0o700),
                                                   (manifest, old_manifest, manifest_body, 0o600)):
                    fd, name = tempfile.mkstemp(prefix=".surge-cc-update-", dir=target.parent)
                    staging = Path(name)
                    with os.fdopen(fd, "wb") as stream:
                        os.fchmod(stream.fileno(), mode)
                        stream.flush()
                    entry = {"target": target, "staging": staging, "old": old,
                             "new": _update_snapshot(staging), "swapped": False}
                    entries.append(entry)
                    # In particular, a failed manifest write happens with the new
                    # shim installed and exercises the same fail-closed rollback.
                    _write_private(staging, contents, mode=mode)
                    entry["new"] = _update_snapshot(staging)
                    if entry["new"][1] != contents:
                        raise Blocked("终端更新临时文件发生变化，已取消更新。")
                    _exchange(staging, target)
                    entry["swapped"] = True
                    if (not _update_matches(staging, old)
                            or not _update_matches(target, entry["new"])):
                        raise Blocked("终端更新期间入口或记录发生变化，已取消更新；请检查当前入口。")
                if _read(folder) != updated:
                    raise Blocked("终端更新记录发生变化，已取消更新。")
                _verify_active(updated)
                result = status(state_dir=folder)
                if not result["ok"]:
                    raise Blocked(result["summary"])
                committed = True
                return result
            finally:
                if not committed:
                    for entry in reversed(entries):
                        if entry["swapped"]:
                            try:
                                _update_restore(entry)
                            except (OSError, ValueError, Blocked):
                                # Preserve displaced originals for recovery when
                                # rollback cannot safely restore the public entry.
                                pass
                for entry in entries:
                    expected = entry["old"] if committed else entry["new"]
                    if _update_matches(entry["staging"], expected):
                        try:
                            entry["staging"].unlink()
                        except OSError:
                            pass  # A retained private backup does not invalidate commit.
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError, Blocked) as error:
        raise _safe_error(error) from None


def uninstall(*, state_dir=None) -> dict:
    folder = _state_dir(state_dir)
    try:
        if not folder.exists() and not folder.is_symlink():
            return {"ok": True, "installed": False, "summary": "终端入口保护未安装。"}
        with _lock(folder):
            if not (folder / "manifest.json").exists() and set(p.name for p in folder.iterdir()) <= {".lock"}:
                return {"ok": True, "installed": False, "summary": "终端入口保护未安装。"}
            data = _read(folder)
            # Restoration can work even after the application backend was removed.
            command = Path(data["command_path"])
            info = _regular(command, executable=True)
            if info.st_uid != os.getuid() or command.read_bytes() != _shim(data):
                raise Blocked("Claude 入口已被修改，拒绝覆盖；请手动确认后恢复。")
            fd, name = tempfile.mkstemp(prefix=".surge-cc-restore-", dir=command.parent)
            os.close(fd)
            temp = Path(name)
            temp.unlink()
            temp.symlink_to(data["original_link"])
            swapped = False
            preserve_displaced = False
            try:
                _exchange(temp, command)
                swapped = True
                displaced = temp.lstat()
                if (temp.is_symlink() or (displaced.st_dev, displaced.st_ino) != (info.st_dev, info.st_ino)
                        or temp.read_bytes() != _shim(data)):
                    preserve_displaced = True
                    if command.is_symlink() and os.readlink(command) == data["original_link"]:
                        _exchange(temp, command)
                        swapped = False
                        preserve_displaced = False
                    raise Blocked("卸载期间 Claude 入口发生变化，已停止恢复。")
                (folder / "manifest.json").unlink()
                (folder / "original-link").unlink()
            finally:
                if os.path.lexists(temp) and not preserve_displaced:
                    temp.unlink()
            return {"ok": True, "installed": False, "summary": "已恢复原始 Claude 命令入口。"}
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError, Blocked) as error:
        raise _safe_error(error) from None


def metadata_version(*, state_dir=None) -> str:
    """Cached local version metadata; never start the Claude native binary."""
    try:
        data = _read(_state_dir(state_dir))
        _verify_active(data)
        return data["native_version"]
    except (OSError, ValueError, TypeError, KeyError, Blocked) as error:
        raise _safe_error(error) from None
